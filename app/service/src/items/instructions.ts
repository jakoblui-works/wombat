// The instructions file: the items of every structure marked `instructions: full` or `index`, rendered from the
// agent view (handles only, never ids, nothing hidden) into `<workspace>/.wombat/AGENTS.md`, outside every repo.
// New agents get it at session start (the harness's `sessionParams`); running ones keep what they started with.
// The service re-renders it at start, after its own writes and approvals, and when a file under the items root
// changes. A render that fails keeps the last good file: a broken item never takes the agents' conventions away.
import { statSync, watch, type FSWatcher } from "node:fs";
import { mkdir, readFile, rm } from "node:fs/promises";
import { dirname, join } from "node:path";

import { errorCode, isMissing } from "@wombat/shared/errno";

import { logToStderr, type Log } from "../log.ts";
import { agentView, type AgentViewItem } from "./access.ts";
import type { Catalog, ValidStructure } from "./catalog.ts";
import { writeAtomic } from "./files.ts";
import { isSkippedPath, SETTINGS_FILE } from "./structures.ts";
import { TOOL } from "./tools.ts";
import { ownValue, parseHandle, propertyOf } from "./validate.ts";
import type { Writer } from "./write.ts";

/** How long the items-root watcher waits after the last change before it re-renders (about 200 ms). */
export const INSTRUCTIONS_DEBOUNCE_MS = 200;

/** Where the instructions file lives, relative to the workspace root: outside every repo. */
export const INSTRUCTIONS_FILE = ".wombat/AGENTS.md";

/** An index entry's line is at most this many characters, "…" included. */
export const INDEX_LINE_MAX = 160;
/** The largest instructions file sent in full; above it every structure is rendered as an index. */
export const INSTRUCTIONS_MAX_BYTES = 64 * 1024;

/** How long a failed watcher first waits before it is started again; the wait doubles while it keeps failing. */
export const WATCH_RESTART_MS = 1_000;
/** The longest wait between restarts of a watcher that keeps failing (e.g. the inotify limit reached). */
export const WATCH_RESTART_MAX_MS = 60_000;
/** How often the watched root is checked for having been removed or replaced. */
export const ROOT_CHECK_MS = 2_000;

/** The directory at a path, as device, inode and birth time: changes when the path is removed and made again
 *  (the inode number alone is often reused at once). Where the filesystem has no birth time it reads 0 and a
 *  replaced root that reuses its inode goes unnoticed until the service restarts. */
const rootIdentity = (path: string) => {
  const { dev, ino, birthtimeNs } = statSync(path, { bigint: true });
  return `${String(dev)}:${String(ino)}:${String(birthtimeNs)}`;
};

export const INSTRUCTIONS_HEADER = "<!-- Generated by Wombat. Read-only: change it through proposals. -->";

const INDEX_NOTE = `Each item below shows its title and first line; read the rest with ${TOOL.getItem} and its handle.`;
const SHORTENED_NOTE = `The instructions are too long to send in full, so each item below shows only its title and first line; read the rest with ${TOOL.getItem} and its handle.`;

/** Handles in natural order: by prefix, then number; anything else by its text. */
const compareHandles = (a: string | null, b: string | null) => {
  const [left, right] = [parseHandle(a), parseHandle(b)];
  if (left !== undefined && right !== undefined) {
    if (left.prefix !== right.prefix) return left.prefix < right.prefix ? -1 : 1;
    return left.number - right.number;
  }
  const [x, y] = [a ?? "", b ?? ""];
  return x < y ? -1 : x > y ? 1 : 0;
};

/** One property's values in a view's sort order: select by option order, links by handle; missing values last. */
const compareValues = (structure: ValidStructure, name: string, a: unknown, b: unknown) => {
  const missing = (value: unknown) => value === undefined || value === null;
  if (missing(a) || missing(b)) return Number(missing(a)) - Number(missing(b));
  const property = propertyOf(structure.settings, name);
  if (property?.type === "select") {
    const rank = (value: unknown) => {
      const index = property.options.indexOf(value as string);
      return index === -1 ? property.options.length : index;
    };
    if (rank(a) !== rank(b)) return rank(a) - rank(b);
  }
  if (property?.type === "link" && typeof a === "string" && typeof b === "string") return compareHandles(a, b);
  if (typeof a === "number" && typeof b === "number") return a - b;
  // An invalid item can hold a list or a map: compared by its JSON, so the order stays stable.
  const text = (value: unknown) => (typeof value === "string" ? value : JSON.stringify(value));
  const [x, y] = [text(a), text(b)];
  return x < y ? -1 : x > y ? 1 : 0;
};

/** The first view's sort if the structure has views, else handle number; ties by handle. */
const ordered = (structure: ValidStructure, items: AgentViewItem[]) => {
  const sort = structure.settings.views[0]?.sort ?? [];
  return [...items].sort((a, b) => {
    for (const name of sort) {
      const order = compareValues(structure, name, ownValue(a.properties, name), ownValue(b.properties, name));
      if (order !== 0) return order;
    }
    return compareHandles(a.handle, b.handle);
  });
};

/** The item's declared properties on one line; links as handles, empty, missing or hidden ones left out. */
const propertyLine = (structure: ValidStructure, item: AgentViewItem) =>
  Object.keys(structure.settings.properties)
    .flatMap((name) => {
      const value = ownValue(item.properties, name);
      if (typeof value === "string" && value.trim() !== "") return [`${name}: ${value.replace(/\s+/g, " ").trim()}`];
      if (typeof value === "number" || typeof value === "boolean") return [`${name}: ${String(value)}`];
      return [];
    })
    .join("; ");

/**
 * The body with blank lines trimmed at both ends and its headings moved three levels down (at most `######`),
 * outside code fences, so a heading in a body never reads as a structure or an item of this file.
 */
const bodyText = (body: string) => {
  let fence: string | undefined;
  const lines = body.split("\n").map((line) => {
    const marker = /^\s{0,3}(`{3,}|~{3,})/.exec(line)?.[1];
    if (marker !== undefined) {
      if (fence === undefined) fence = marker;
      else if (marker.startsWith(fence)) fence = undefined;
      return line;
    }
    if (fence !== undefined) return line;
    return line.replace(/^(\s{0,3})(#{1,6})(?=\s|$)/, (_match, indent: string, hashes: string) => `${indent}${"#".repeat(Math.min(6, hashes.length + 3))}`);
  });
  while (lines.length > 0 && (lines[0] ?? "").trim() === "") lines.shift();
  while (lines.length > 0 && (lines.at(-1) ?? "").trim() === "") lines.pop();
  return lines.join("\n");
};

/** The body's first non-empty line, trimmed and without heading marks, capped at INDEX_LINE_MAX with "…". */
export const indexLine = (body: string | null): string | undefined => {
  const first = (body ?? "")
    .split("\n")
    .map((line) => line.trim().replace(/^#{1,6}\s+/, ""))
    .find((line) => line !== "" && !/^#{1,6}$/.test(line));
  if (first === undefined) return undefined;
  const chars = Array.from(first);
  return chars.length <= INDEX_LINE_MAX ? first : `${chars.slice(0, INDEX_LINE_MAX - 1).join("").trimEnd()}…`;
};

const renderItem = (structure: ValidStructure, item: AgentViewItem, mode: "full" | "index"): string[] => {
  const lines = [`### ${item.handle ?? ""} ${item.title ?? ""}`];
  if (mode === "index") {
    const line = indexLine(item.body);
    if (line !== undefined) lines.push(line);
    return lines;
  }
  const properties = propertyLine(structure, item);
  if (properties !== "") lines.push(properties);
  const body = bodyText(item.body ?? "");
  if (body !== "") lines.push("", body);
  return lines;
};

export type RenderOptions = {
  /** Above this many bytes every structure is rendered as an index, so no structure can crowd out an agent's prompt. */
  maxBytes?: number;
};

/** The instructions file's text from the catalog's current read, or undefined when no structure is marked. */
export const renderInstructions = async (catalog: Catalog, { maxBytes = INSTRUCTIONS_MAX_BYTES }: RenderOptions = {}): Promise<string | undefined> => {
  const { structures, items } = agentView(await catalog.snapshot());
  const marked = structures.filter((structure) => structure.settings.instructions !== "off").sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
  if (marked.length === 0) return undefined;
  const render = (shortened: boolean) => {
    const sections = marked.map((structure) => {
      const mode = shortened ? "index" : (structure.settings.instructions as "full" | "index");
      // D28: an item renders when it has a title and a handle, value problems or not; its problems never do.
      const own = items.filter((item) => item.structure === structure.id && item.handle !== null && item.title !== null);
      const lines = [`## ${structure.settings.name}`];
      if (mode === "index") lines.push("", shortened && structure.settings.instructions === "full" ? SHORTENED_NOTE : INDEX_NOTE);
      for (const item of ordered(structure, own)) lines.push("", ...renderItem(structure, item, mode));
      return lines.join("\n");
    });
    return `${[INSTRUCTIONS_HEADER, ...sections].join("\n\n")}\n`;
  };
  const full = render(false);
  return Buffer.byteLength(full) <= maxBytes ? full : render(true);
};

export type WriteInstructionsOptions = {
  /** Undefined when the items aren't configured: nothing is rendered and a stale file is removed. */
  catalog: Catalog | undefined;
  workspaceRoot: string;
  log?: Log;
};

const readCurrent = async (path: string) => {
  try {
    return await readFile(path, "utf8");
  } catch {
    return undefined;
  }
};

/**
 * Renders and writes `<workspaceRoot>/.wombat/AGENTS.md` (atomic, mode 0444), or removes a stale one when there's
 * nothing to render. A render failure is logged as `instructions_failed` and keeps the last good file.
 */
export const writeInstructions = async ({ catalog, workspaceRoot, log = logToStderr }: WriteInstructionsOptions): Promise<void> => {
  const path = join(workspaceRoot, INSTRUCTIONS_FILE);
  let text: string | undefined;
  try {
    text = catalog === undefined ? undefined : await renderInstructions(catalog);
  } catch (error) {
    log("instructions_failed", { step: "render", error: errorCode(error) });
    return;
  }
  const current = await readCurrent(path);
  if (text === undefined) {
    if (current === undefined) return;
    try {
      await rm(path, { force: true });
      log("instructions_removed", {});
    } catch (error) {
      log("instructions_failed", { step: "remove", error: errorCode(error) });
    }
    return;
  }
  // Nothing changed: the file stays as it is, so watchers of it see no write.
  if (current === text) return;
  try {
    await mkdir(dirname(path), { recursive: true });
    // Replacing the old read-only file by rename needs only the folder writable.
    await writeAtomic(path, text, { mode: 0o444 });
    log("instructions_written", { bytes: Buffer.byteLength(text) });
  } catch (error) {
    log("instructions_failed", { step: "write", error: errorCode(error) });
  }
};

/** The instructions file's text, or undefined when there is none (or it's empty): then nothing is sent to an agent. */
export const readInstructions = async (workspaceRoot: string, log: Log = logToStderr): Promise<string | undefined> => {
  try {
    const text = await readFile(join(workspaceRoot, INSTRUCTIONS_FILE), "utf8");
    return text === "" ? undefined : text;
  } catch (error) {
    if (!isMissing(error)) log("instructions_unreadable", { error: errorCode(error) });
    return undefined;
  }
};

export type InstructionsOptions = {
  catalog: Catalog | undefined;
  workspaceRoot: string;
  /** Watched for changes; undefined when the items aren't configured. */
  itemsRoot: string | undefined;
  log?: Log;
};

export type Instructions = {
  /** Renders and writes the file; resolves once this call's changes are in it. Never rejects. */
  refresh: () => Promise<void>;
  /** Starts the recursive watch of the items root (no-op without one). */
  watch: () => void;
  /** Stops watching and waits for a render in progress. */
  close: () => Promise<void>;
};

/** True for a changed path (relative to the items root) that can change the file: an item or a structure's settings. */
const relevant = (filename: string | null) => {
  if (filename === null) return true;
  const parts = filename.split(/[\\/]/);
  if (isSkippedPath(parts.join("/"))) return false;
  const name = parts.at(-1) ?? "";
  return name.endsWith(".md") || name === SETTINGS_FILE;
};

/** The instructions file in the service: renders one at a time, coalesced, and a debounced watcher of the items root. */
export const openInstructions = ({ catalog, workspaceRoot, itemsRoot, log = logToStderr }: InstructionsOptions): Instructions => {
  let running: Promise<void> = Promise.resolve();
  let queued: Promise<void> | undefined;
  let closed = false;
  let watcher: FSWatcher | undefined;
  let debounce: NodeJS.Timeout | undefined;
  let restart: NodeJS.Timeout | undefined;
  let rootCheck: NodeJS.Timeout | undefined;

  const refresh = () => {
    // A render that hasn't started yet reads the root after this call, so it covers this call's changes too.
    if (queued !== undefined) return queued;
    const next = running.then(async () => {
      queued = undefined;
      await writeInstructions({ catalog, workspaceRoot, log }).catch((error: unknown) => {
        log("instructions_failed", { step: "unexpected", error: errorCode(error) });
      });
    });
    queued = next;
    running = next;
    return next;
  };

  const schedule = () => {
    clearTimeout(debounce);
    debounce = setTimeout(() => void refresh(), INSTRUCTIONS_DEBOUNCE_MS);
  };

  // While starting the watcher keeps failing (e.g. the inotify limit), the wait doubles and the failure is logged
  // once, not on every attempt; a start that works resets both.
  let retryMs = WATCH_RESTART_MS;
  let failing = false;

  const start = () => {
    if (closed || itemsRoot === undefined) return;
    const retry = (error: unknown) => {
      clearInterval(rootCheck);
      watcher?.close();
      watcher = undefined;
      if (!failing) log("instructions_watch_failed", { error: errorCode(error), retryMs });
      failing = true;
      clearTimeout(restart);
      const wait = retryMs;
      retryMs = Math.min(retryMs * 2, WATCH_RESTART_MAX_MS);
      restart = setTimeout(() => {
        if (closed) return;
        start();
        if (watcher !== undefined) {
          log("instructions_watch_restarted", {});
          failing = false;
          retryMs = WATCH_RESTART_MS;
          // Changes while nothing watched are caught up here; not while the root is missing, which would
          // remove the file for as long as a re-clone takes.
          schedule();
        }
      }, wait);
    };
    try {
      const identity = rootIdentity(itemsRoot);
      watcher = watch(itemsRoot, { recursive: true }, (_event, filename) => {
        if (relevant(filename)) schedule();
      });
      watcher.on("error", retry);
      // A root that is removed and put back (a re-clone) leaves the watch on the old directory with no error and
      // no further events, so the path is checked now and then and the watch restarted when it points elsewhere.
      clearInterval(rootCheck);
      rootCheck = setInterval(() => {
        let now: string | undefined;
        try {
          now = rootIdentity(itemsRoot);
        } catch {
          now = undefined;
        }
        if (now !== identity) {
          clearInterval(rootCheck);
          retry(Object.assign(new Error("the items root was moved or replaced"), { code: "ROOT_REPLACED" }));
        }
      }, ROOT_CHECK_MS);
      rootCheck.unref();
    } catch (error) {
      retry(error);
    }
  };

  return {
    refresh,
    watch: start,
    close: async () => {
      closed = true;
      clearTimeout(debounce);
      clearTimeout(restart);
      clearInterval(rootCheck);
      watcher?.close();
      watcher = undefined;
      await running;
    },
  };
};

/** The writer with the instructions file refreshed after each write, before the write's call answers. */
export const refreshingWriter = (writer: Writer, refresh: () => Promise<void>): Writer => ({
  createItem: async (structureId, item) => {
    const created = await writer.createItem(structureId, item);
    await refresh();
    return created;
  },
  updateItem: async (handle, fields, baseVersion) => {
    const updated = await writer.updateItem(handle, fields, baseVersion);
    await refresh();
    return updated;
  },
  deleteItem: async (handle, baseVersion) => {
    await writer.deleteItem(handle, baseVersion);
    await refresh();
  },
  checkNewFile: (structureId, file, unseen) => writer.checkNewFile(structureId, file, unseen),
  check: (change) => writer.check(change),
});
