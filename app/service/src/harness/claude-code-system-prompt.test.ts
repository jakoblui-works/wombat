// Contract drift check: what the Claude Code harness asks to put into session/new for the instructions is
// what claude-agent-acp 0.100.0 turns into Claude Code's own preset prompt with the text appended, run through the
// package's own conversion, so a wrong shape (one that replaces Claude Code's prompt, or is dropped) shows here.
import { clientSystemPrompt, sdkSystemPrompt } from "@agentclientprotocol/claude-agent-acp/dist/client-system-prompt.js";
import { describe, expect, test } from "vitest";

import { claudeCode } from "./claude-code.ts";

describe("the Claude Code harness's instructions", () => {
  test("are appended to Claude Code's preset prompt by claude-agent-acp, unchanged, and never through _meta", () => {
    const instructions = [
      "<!-- Generated by Wombat. Read-only: change it through proposals. -->",
      "",
      "## Conventions",
      "",
      "### CONV-1 Name branches after the task",
      "area: services",
      "",
      "Use the task's handle in the branch name.",
      "",
    ].join("\n");

    expect(claudeCode.sessionParams, "the Claude Code harness asks for the instructions").toBeDefined();
    const params = claudeCode.sessionParams?.(instructions) ?? {};

    // The package's own path from session/new's `systemPrompt` to the SDK option (acp-agent.js, newSession).
    const client = clientSystemPrompt(params.systemPrompt as Parameters<typeof clientSystemPrompt>[0]);
    expect(client, "a systemPrompt the package reads").toBeDefined();
    expect(sdkSystemPrompt(client as NonNullable<typeof client>, undefined)).toEqual({ type: "preset", preset: "claude_code", append: instructions });
    expect(Object.keys(params), "only the systemPrompt").toEqual(["systemPrompt"]);
  });
});
